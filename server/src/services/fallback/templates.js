export function render(lang, key, vars = {}) {
  const table = T[lang] ?? T.en;
  const tpl = key.split('.').reduce((o, k) => o?.[k], table) ?? key.split('.').reduce((o, k) => o?.[k], T.en);
  return String(tpl).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

